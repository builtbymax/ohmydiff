#!/usr/bin/env python3
"""Imports a subset of the Catppuccin file icons (https://github.com/catppuccin/vscode-icons, MIT).

    git clone --depth 1 https://github.com/catppuccin/vscode-icons.git /tmp/catppuccin-icons
    scripts/catppuccin-icons.py /tmp/catppuccin-icons

Writes one image set per icon to ohmydiff/Assets.xcassets/FileIcons, Latte for light and Mocha for dark,
and the file names and extensions that pick them to ohmydiff/Views/FileIconCatalog.swift. Add an icon by
adding its name to ICONS and running the script again.
"""
import json
import pathlib
import re
import shutil
import sys

ICONS = [
    "_file",
    # Languages
    "typescript", "typescript-react", "typescript-test", "typescript-def", "javascript", "javascript-react",
    "javascript-test", "swift", "python", "go", "rust", "ruby", "java", "kotlin", "c", "c-header", "cpp",
    "cpp-header", "csharp", "php", "dart", "lua", "elixir", "zig", "vue", "svelte", "astro", "html", "css",
    "sass", "less", "bash", "database", "graphql", "proto", "nix", "terraform", "prisma",
    # Data and docs
    "json", "yaml", "toml", "xml", "markdown", "markdown-mdx", "text", "csv", "pdf", "changelog", "contributing",
    "license", "readme",
    # Media
    "svg", "image", "font", "audio", "video", "zip", "binary", "certificate",
    # Tooling
    "lock", "docker", "makefile", "git", "env", "editorconfig", "package-json", "npm", "npm-lock", "pnpm",
    "pnpm-lock", "yarn", "yarn-lock", "bun", "bun-lock", "typescript-config", "javascript-config", "vite",
    "eslint", "prettier", "tailwind", "next", "turbo", "biome", "vercel", "jest", "vitest", "storybook",
    "gradle", "cargo", "cargo-lock", "go-mod", "deno", "drizzle-orm", "xcode", "ruby-gem", "apple",
]

root = pathlib.Path(__file__).resolve().parent.parent
source = pathlib.Path(sys.argv[1])
catalog = root / "ohmydiff/Assets.xcassets/FileIcons"
swift = root / "ohmydiff/Views/FileIconCatalog.swift"

defaults = (source / "src/defaults/fileIcons.ts").read_text()
by_name: dict[str, str] = {}
by_extension: dict[str, str] = {}
for match in re.finditer(r"^  '?([\w-]+)'?: \{(.*?)^  \},", defaults, re.M | re.S):
    icon, body = match.groups()
    if icon not in ICONS:
        continue
    for key, table in (("fileNames", by_name), ("fileExtensions", by_extension)):
        values = re.search(key + r":\s*\[(.*?)\]", body, re.S)
        for value in re.findall(r"'([^']+)'", values.group(1)) if values else []:
            table.setdefault(value.lower(), icon)

shutil.rmtree(catalog, ignore_errors=True)
catalog.mkdir(parents=True)
(catalog / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}}, indent=2) + "\n")
for icon in ICONS:
    folder = catalog / f"{icon}.imageset"
    folder.mkdir()
    shutil.copy(source / f"icons/latte/{icon}.svg", folder / f"{icon}.svg")
    shutil.copy(source / f"icons/mocha/{icon}.svg", folder / f"{icon}-dark.svg")
    (folder / "Contents.json").write_text(json.dumps({
        "images": [
            {"filename": f"{icon}.svg", "idiom": "universal"},
            {"appearances": [{"appearance": "luminosity", "value": "dark"}], "filename": f"{icon}-dark.svg", "idiom": "universal"},
        ],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True},
    }, indent=2) + "\n")


def entries(table: dict[str, str]) -> str:
    return "\n".join(f'        "{key}": "{icon}",' for key, icon in sorted(table.items()))


swift.write_text(f"""// Generated by scripts/catppuccin-icons.py from catppuccin/vscode-icons (MIT). Do not edit.

extension FileIcon {{
    static let byName: [String: String] = [
{entries(by_name)}
    ]

    static let byExtension: [String: String] = [
{entries(by_extension)}
    ]
}}
""")
print(f"{len(ICONS)} icons, {len(by_name)} file names, {len(by_extension)} extensions")
